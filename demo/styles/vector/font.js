// Advance per glyph is 6 grid units at size s (s = glyph height in px / 6).
export const textWidth = (str, px) => (str.length * 6 - 2) * (px / 6);

// Draws `str` with its top-left at (x, y); align "c" centers it, "r" right-aligns it.
export function text(beam, str, x, y, px, col, I, align = "l") {
  const s = px / 6;
  if (align === "c") x -= textWidth(str, px) / 2;
  else if (align === "r") x -= textWidth(str, px);
  for (const ch of str.toUpperCase()) {
    const g = G[ch];
    if (g) for (const line of g) {
      const p = new Array(line.length);
      for (let k = 0; k < line.length; k += 2) { p[k] = x + line[k] * s; p[k + 1] = y + line[k + 1] * s; }
      beam.poly(p, false, col, I, { ends: true });
    }
    x += 6 * s;
  }
}
