const FONT = Object.fromEntries(Object.entries(GLYPHS).map(([k, v]) => [k, v.split(" ").map((r) => parseInt(r, 2))]));

function put(B, x, y, c) { if (x >= 0 && y >= 0 && x < B.w && y < B.h) B.c[y * B.w + x] = c; }
function fill(B, x0, y0, x1, y1, c) { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) put(B, x, y, c); }
export function text(B, s, x, y, c) {
  for (const ch of s.toUpperCase()) {
    const g = FONT[ch] || FONT[" "];
    g.forEach((row, j) => { for (let i = 0; i < 5; i++) if (row & (16 >> i)) put(B, x + i, y + j, c); });
    x += ch === " " ? 4 : 6;
  }
  return x;
}
const width = (s) => [...s].reduce((a, ch) => a + (ch === " " ? 4 : 6), 0);
function bevel(B, x0, y0, x1, y1, sunk) {
  fill(B, x0, y0, x1, y1, sunk ? P.r3 : P.r4);
  fill(B, x0, y0, x1, y0, sunk ? P.r1 : P.r5); fill(B, x0, y0, x0, y1, sunk ? P.r1 : P.r5);
  fill(B, x0, y1, x1, y1, sunk ? P.r5 : P.r1); fill(B, x1, y0, x1, y1, sunk ? P.r5 : P.r1);
}

export function drawUI(B, right, info) {
  bevel(B, 0, 0, B.w - 1, 11, false);
  fill(B, 0, 12, B.w - 1, 12, P.ink);
  let x = 6;
  for (const item of ["File", "Speed", "Options", "Windows", "Help"]) x = text(B, item, x, 3, P.ink) + 10;
  const rw = width(right) + 10;
  bevel(B, B.w - rw - 4, 2, B.w - 5, 10, true);
  text(B, right, B.w - rw + 1, 3, P.ink);
  const iw = width(info) + 12, y0 = B.h - 15;
  fill(B, 3, y0 - 1, iw + 5, B.h - 2, P.ink);
  bevel(B, 4, y0, iw + 4, B.h - 3, false);
  bevel(B, 7, y0 + 2, iw + 1, B.h - 5, true);
  text(B, info, 10, y0 + 3, P.ink);
}
